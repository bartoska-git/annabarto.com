                <h2>4. Site prototyping with AI tools (and when things broke)</h2>

                <p>For prototyping, I used <strong>Magic Patterns</strong>, one of several AI prototyping tools I'd explored during <a href="https://www.reforge.com/courses/ai-productivity" class="inline-link" target="_blank" rel="noopener noreferrer">Reforge's AI Productivity course</a> (alongside Lovable, Bolt, v0).</p>

                <p>Magic Patterns' strength is exploration, especially its Inspiration mode, which generates multiple design variations from the same inputs.</p>

                <p>I fed it the wireframes and visual assets, then iterated extensively. The project reached around 80% complete.</p>

                <p>Then <strong>on December 24th, Magic Patterns rolled out an update</strong>. Previously working prompts stopped producing usable results. I contacted support, got a rollback and extra credits, but issues persisted for days.</p>

                <figure style="margin: var(--space-xl) 0; border-radius: var(--radius-md); overflow: hidden; box-shadow: var(--shadow-soft);">
