                <h2>3. Visual identity: the cartoonification experiment</h2>

                <p>I decided early to use an illustrated portrait instead of a photograph, aiming for a flat, editorial-style aesthetic with a New Yorker-inspired feel.</p>

                <p>I tested Midjourney, DALL·E, Canva, and many tools from <a href="https://www.successtechservices.com/ai-cartoonizers/" class="inline-link" target="_blank" rel="noopener noreferrer">this AI cartoonizer roundup</a>. Despite extensive prompt iteration (often with ChatGPT's help), results were inconsistent.</p>

                <p><strong>Artlist.io</strong> ultimately worked best, producing the closest match to what I had envisioned. I used it for the portrait and case study thumbnails to keep visual language consistent.</p>

                <p>One limitation: Artlist (like most AI image tools) doesn't produce transparent PNGs, requiring post-processing in Photoshop.</p>

